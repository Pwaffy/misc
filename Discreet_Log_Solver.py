# Solves discreet log in finite field

from sage.all import GF,ZZ
import sympy


def solve(a, b, p):
    p = ZZ(p)
    a = ZZ(a) % p
    b = ZZ(b) % p

    F = GF(p)
    base = F(a)
    target = F(b)

    n = ZZ(target.log(base))
    print(f"Answer = {n}\n{a}^{n} mod {p} = {b}\n")

